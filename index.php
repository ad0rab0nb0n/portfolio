<script>
    // Accessible mobile navigation.
    const menuButton = document.querySelector('.menu-toggle');
    const navLinks = document.querySelector('.nav-links');

    if (menuButton && navLinks) {
        menuButton.addEventListener('click', () => {
            const isOpen = navLinks.classList.toggle('open');
            menuButton.setAttribute('aria-expanded', String(isOpen));
        });

        navLinks.querySelectorAll('a').forEach((link) => {
            link.addEventListener('click', () => {
                navLinks.classList.remove('open');
                menuButton.setAttribute('aria-expanded', 'false');
            });
        });
    }

    // Reveal sections and cards smoothly as the visitor scrolls down.
    // The homepage keeps just one portrait photo in the hero section.
    document.addEventListener('DOMContentLoaded', () => {
        const revealSelectors = [
            '.section-head',
            '.about-card',
            '.about-copy',
            '.skill-card',
            '.project-card',
            '.credential-card',
            '.timeline-item',
            '.education-item',
            '.contact-panel'
        ];

        if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
            return;
        }

        revealSelectors.forEach((selector) => {
            document.querySelectorAll(selector).forEach((element) => {
                element.classList.add('reveal-on-scroll');
            });
        });

        // Stagger cards in each grid for a gentle cascading effect.
        [
            '.skills-grid',
            '.project-grid',
            '.credentials-grid',
            '.timeline',
            '.education-grid'
        ].forEach((gridSelector) => {
            document.querySelectorAll(gridSelector).forEach((grid) => {
                const cards = grid.querySelectorAll(
                    '.skill-card, .project-card, .credential-card, .timeline-item, .education-item'
                );
                cards.forEach((card, index) => {
                    card.style.setProperty('--reveal-delay', `${Math.min(index * 85, 340)}ms`);
                });
            });
        });

        if (!('IntersectionObserver' in window)) {
            document.querySelectorAll('.reveal-on-scroll').forEach((element) => {
                element.classList.add('is-visible');
            });
            return;
        }

        const observer = new IntersectionObserver((entries, currentObserver) => {
            entries.forEach((entry) => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('is-visible');
                    currentObserver.unobserve(entry.target);
                }
            });
        }, {
            threshold: 0.12,
            rootMargin: '0px 0px -40px 0px'
        });

        document.querySelectorAll('.reveal-on-scroll').forEach((element) => {
            observer.observe(element);
        });
    });
</script>
